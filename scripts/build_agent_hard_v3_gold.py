def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--questions",
        type=Path,
        default=Path("data/evaluation/agent-hard-v3-questions.json"),
    )
    parser.add_argument(
        "--source-manifest",
        type=Path,
        default=Path("data/evaluation/agent-hard-v3-source-manifest.json"),
    )
    parser.add_argument(
        "--spec-dir",
        type=Path,
        default=Path("data/evaluation/agent-hard-v3-gold-specs"),
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("data/evaluation/agent-hard-v3.json"),
    )
    return parser.parse_args()


def fact(
    fact_id: str,
    description: str,
    acceptable_values: list[str],
    unit: str | None = None,
) -> AgentHardExpectedFact:
    return AgentHardExpectedFact(
        fact_id=fact_id,
        description=description,
        acceptable_values=acceptable_values,
        unit=unit,
    )


def spec(
    facts: list[AgentHardExpectedFact],
    sources: list[tuple[str, list[int]]],
    rationale: str,
) -> dict[str, Any]:
    return {"facts": facts, "sources": sources, "rationale": rationale}


