def _question_payload_sha256(questions: list[dict[str, Any]]) -> str:
    blind_payload = [
        {
            "case_id": item["case_id"],
            "task_type": item["task_type"],
            "agent_command": item["agent_command"],
            "query": item["query"],
        }
        for item in questions
    ]
    payload = json.dumps(
        blind_payload,
        ensure_ascii=False,
        sort_keys=True,
        separators=(",", ":"),
    )
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()


def _expected_target_ids(question: dict[str, Any]) -> list[str]:
    if question["task_type"] != "compare":
        return []
    return [
        f"company:{question['company_name']}:year:{year}"
        for year in question["report_years"]
    ]


def _build_case(
    question: dict[str, Any],
    *,
    manifest_by_key: dict[str, dict[str, Any]],
) -> AgentHardCase:
    response_mode = question["expected_response_mode"]
    if response_mode == "clarify":
        return AgentHardCase(
            case_id=question["case_id"],
            task_type=question["task_type"],
            query=question["query"],
            challenge_types=question["challenge_types"],
            expected_behavior="clarify",
            expected_target_ids=[],
            expected_facts=[],
            evidence_sources=[],
            gold_rationale=(
                "问题没有唯一给出公司、比较年度和指标口径；应先追问，不应自行假定。"
            ),
            annotation_status="assistant_source_verified_provisional",
        )
    if question["expected_behavior"] == "abstain":
        return AgentHardCase(
            case_id=question["case_id"],
            task_type=question["task_type"],
            query=question["query"],
            challenge_types=question["challenge_types"],
            expected_behavior="abstain",
            expected_target_ids=[],
            expected_facts=[],
            evidence_sources=[],
            gold_rationale=(
                "冻结语料仅包含2023年和2024年年报，不能给出2025年实际全年值或伪造页码。"
            ),
            annotation_status="assistant_source_verified_provisional",
        )
    item = GOLD[question["case_id"]]
    evidence_sources = []
    for document_key, pages in item["sources"]:
        document = manifest_by_key[document_key]
        evidence_sources.append(
            AgentHardEvidenceSource(
                document_key=document_key,
                local_file=document["local_file"],
                pages=pages,
            )
        )
    return AgentHardCase(
        case_id=question["case_id"],
        task_type=question["task_type"],
        query=question["query"],
        challenge_types=question["challenge_types"],
        expected_behavior="answer",
        expected_target_ids=_expected_target_ids(question),
        expected_facts=item["facts"],
        evidence_sources=evidence_sources,
        gold_rationale=item["rationale"],
        annotation_status="assistant_source_verified_provisional",
    )


def build_dataset(
    questions_path: Path,
    source_manifest_path: Path,
) -> AgentHardDataset:
    question_bank = json.loads(questions_path.read_text(encoding="utf-8"))
    questions = question_bank["questions"]
    actual_hash = _question_payload_sha256(questions)
    if actual_hash != question_bank["question_payload_sha256"]:
        raise ValueError("Question payload hash does not match the frozen bank")
    manifest = json.loads(source_manifest_path.read_text(encoding="utf-8"))
    manifest_by_key = {
        document["document_key"]: document for document in manifest["documents"]
    }
    answer_ids = {
        question["case_id"]
        for question in questions
        if question["expected_behavior"] == "answer"
    }
    missing = sorted(answer_ids - GOLD.keys())
    unexpected = sorted(GOLD.keys() - answer_ids)
    if missing or unexpected:
        raise ValueError(f"Gold coverage mismatch: missing={missing}, unexpected={unexpected}")
    return AgentHardDataset(
        schema_version="1",
        dataset_id="agent-hard-v3-external-provisional-gold",
        description=(
            "Ninety-six company- and document-blind Agent tasks over sixteen official "
            "CNINFO annual reports. Facts and pages are source-verified provisional gold; "
            "independent double review remains pending."
        ),
        index_scope="agent-hard-v3 immutable index; eight companies, 2023 and 2024",
        source_manifest=source_manifest_path.as_posix(),
        gold_policy=(
            "Gold was transcribed before the first Agent run. No evaluated Agent, DeepSeek "
            "answer, or LLM judge was used to create it. Exact values, deterministic behavior "
            "checks, and page-bound citations are scored locally."
        ),
        cases=[
            _build_case(question, manifest_by_key=manifest_by_key)
            for question in questions
        ],
    )


def _write_company_specs(dataset: AgentHardDataset, spec_dir: Path) -> None:
    spec_dir.mkdir(parents=True, exist_ok=True)
    by_company: dict[str, list[dict[str, Any]]] = {}
    for case in dataset.cases:
        company_code = case.case_id.split("_")[1]
        by_company.setdefault(company_code, []).append(case.model_dump(mode="json"))
    for company_code, cases in by_company.items():
        payload = {
            "schema_version": "1",
            "security_code": company_code,
            "annotation_status": "assistant_source_verified_provisional",
            "independent_double_review_complete": False,
            "cases": cases,
        }
        (spec_dir / f"{company_code}.json").write_text(
            json.dumps(payload, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )


def main() -> int:
    args = parse_args()
    dataset = build_dataset(args.questions, args.source_manifest)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(dataset.model_dump_json(indent=2) + "\n", encoding="utf-8")
    _write_company_specs(dataset, args.spec_dir)
    behavior_counts: dict[str, int] = {}
    for case in dataset.cases:
        behavior_counts[case.expected_behavior] = (
            behavior_counts.get(case.expected_behavior, 0) + 1
        )
    print(f"cases={len(dataset.cases)}")
    print(f"gold_answer_specs={len(GOLD)}")
    print(f"behavior_counts={json.dumps(behavior_counts, sort_keys=True)}")
    print(f"output={args.output.resolve()}")
    return 0


